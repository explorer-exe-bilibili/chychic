/** pin 为触发 EXTI 的引脚位掩码。编码器 A 相上升沿时读取 B 相。 */
void HAL_GPIO_EXTI_Callback(uint16_t pin)
{
  if (pin == GPIO_PIN_4)
  {
    bsp_lift_encoder_on_a_edge();
  }
}

